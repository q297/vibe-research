"""Events produced by ingestion (role 2)

An event is a cluster of articles (A2); the list view carries no full text (D13, H2)
"""

from datetime import datetime
from enum import StrEnum

from pydantic import Field

from app.contracts.common import SCHEMA_VERSION, Contract
from app.contracts.taxonomy import TAXONOMY_VERSION, SensitivityTag


class ClassificationStatus(StrEnum):
    CLASSIFIED = "classified"
    UNCLASSIFIED = "unclassified"
    FAILED = "failed"


class EventOrigin(StrEnum):
    FEED = "feed"
    USER_INPUT = "user_input"
    SYNTHETIC = "synthetic"


class ArticleRef(Contract):
    article_id: str = Field(description="Hash of the canonical URL without utm params (D1)")
    title: str
    source_name: str
    url: str | None = None
    published_at: datetime | None = None
    snippet: str | None = Field(default=None, max_length=400)


class Entity(Contract):
    name: str = Field(description="Normalized name")
    kind: str = Field(description="company, person, country, commodity, regulator, other")


class EventBase(Contract):
    schema_version: str = SCHEMA_VERSION
    event_id: str
    version: int = Field(default=1, description="Bumped when the cluster changes (F2)")
    merged_into: str | None = Field(default=None, description="Set when the event was merged")
    title: str
    summary: str | None = Field(default=None, description="Generated by a model, never a fact")
    event_type: str | None = None
    tags: list[SensitivityTag] = Field(default_factory=list)
    keywords: list[str] = Field(default_factory=list)
    okved_sections: list[str] = Field(
        default_factory=list, description="OKVED codes, '*' means the whole economy (D3)"
    )
    countries: list[str] = Field(default_factory=list, description="ISO 3166-1 alpha-2 (D4)")
    regions: list[str] = Field(default_factory=list, description="Russian regions as in client CSV")
    importance: float | None = Field(
        default=None, ge=0, le=1, description="Client-independent importance (D9)"
    )
    published_at: datetime | None = None
    ingested_at: datetime
    updated_at: datetime
    classification_status: ClassificationStatus = ClassificationStatus.CLASSIFIED
    origin: EventOrigin = EventOrigin.FEED
    taxonomy_version: str = TAXONOMY_VERSION


class EventListItem(EventBase):
    source_count: int = 1


class Event(EventBase):
    entities: list[Entity] = Field(default_factory=list)
    articles: list[ArticleRef] = Field(default_factory=list)


class NewsIngestRequest(Contract):
    """User-submitted news for the live demo (E4); the text is untrusted (H3)"""

    text: str = Field(min_length=40, max_length=10_000)
    title: str | None = Field(default=None, max_length=300)
    url: str | None = Field(default=None, max_length=2_000)
    client_id: str | None = Field(
        default=None, description="If set, insight generation starts right away"
    )


class NewsIngestResponse(Contract):
    event: Event
    job_id: str | None = None
